"""The architecture drawings page on GitHub Pages matches the docs it is built from.

docs/architecture-drawings.html is generated by docs/site/drawings/build.py from the Mermaid
drawings in docs/. These tests fail when a doc changes without the page being rebuilt, so
the public page never drifts from the docs.
"""
import importlib.util
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
BUILD = ROOT / "docs" / "site" / "drawings" / "build.py"
PAGE = ROOT / "docs" / "architecture-drawings.html"


def load_build():
    spec = importlib.util.spec_from_file_location("drawings_build", BUILD)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def test_committed_page_matches_a_fresh_build():
    build = load_build()
    assert PAGE.read_text(encoding="utf-8") == build.build(), (
        "docs/architecture-drawings.html is out of date: run python docs/site/drawings/build.py")


def test_build_is_repeatable():
    build = load_build()
    assert build.build() == build.build()


def test_every_mermaid_drawing_in_the_docs_is_on_the_page():
    build = load_build()
    page = PAGE.read_text(encoding="utf-8")
    blocks = sum(len(re.findall(r"^```mermaid\s*$", (ROOT / p).read_text(encoding="utf-8"), re.M))
                 for p, _, _ in build.DOCS)
    assert page.count('<pre class="mermaid">') == blocks


def test_page_says_the_data_is_synthetic():
    page = PAGE.read_text(encoding="utf-8")
    assert "Synthetic data only." in page
    assert "illustrative, not cited" in page


ALLOWED_LINKS = (
    "#",
    "https://github.com/voneeci/fjordvik",  # the docs and repository
    "https://fonts.googleapis.com",          # the page's fonts
    "https://c4model.com/",                  # the method the concepts section cites
)


def test_page_links_only_to_the_repository_or_named_references():
    page = PAGE.read_text(encoding="utf-8")
    for href in re.findall(r'href="([^"]+)"', page):
        assert href.startswith(ALLOWED_LINKS), f"unexpected link {href}: add it to ALLOWED_LINKS if it belongs"


def test_page_loads_a_pinned_mermaid_version():
    page = PAGE.read_text(encoding="utf-8")
    assert re.search(r"cdn\.jsdelivr\.net/npm/mermaid@\d+\.\d+\.\d+/", page)
